# T7. Borough descriptives, straight off the exposure table.
# ---------------------------------------------------------------------------------------
BORO = {"36061": "Manhattan", "36047": "Brooklyn", "36081": "Queens", "36005": "Bronx", "36085": "Staten Island"}


def _table() -> pd.DataFrame:
    """The joined per-block-group table, with the columns this module needs coerced to numbers."""
    df = pd.read_csv(EXPOSURE / "exposure_table_nyc.csv", dtype={"GEOID": str})
    for c in ("population", "R_i", "A_drive", "A_modal", "A_mnl", "E_i", "median_hh_income"):
        if c in df.columns:
            df[c] = pd.to_numeric(df[c], errors="coerce")
    return df[df["population"] > 0].copy()


def t_descriptives() -> str:
    df = _table()
    cols = [c for c in ("R_i", "A_mnl", "E_i") if c in df.columns]
    df["boro"] = df["GEOID"].str[:5]

    def wmean(g: pd.DataFrame, c: str) -> float:
        v, w = g[c], g["population"]
        m = v.notna()
        return float(np.average(v[m], weights=w[m])) if m.any() else float("nan")

    header = "    Borough & Block groups & Population & " + " & ".join(
        {"R_i": r"$R_i$", "A_mnl": r"$A_i^{\text{MNL}}$", "E_i": r"$E_i$"}[c] for c in cols
    )
    body = header + " \\\\\n    \\midrule\n"
    for code, name in BORO.items():
        g = df[df.boro == code]
        if g.empty:
            continue
        cells = " & ".join(f"{wmean(g, c):.1f}" for c in cols)
        body += f"    {name} & {len(g):,} & {g['population'].sum() / 1e6:.2f}M & {cells} \\\\\n"
    body += "    \\midrule\n"
    cells = " & ".join(f"{wmean(df, c):.1f}" for c in cols)
    body += f"    \\textbf{{Citywide}} & {len(df):,} & {df['population'].sum() / 1e6:.2f}M & {cells} \\\\\n"
    n_zero = int((df["R_i"] == 0).sum())
    pop_zero = int(df.loc[df["R_i"] == 0, "population"].sum())
    note = (
        "Population-weighted mean distinct cameras. $R_i$ counts cameras whose field of view covers any "
        "street point reachable in a 10-minute walk of the block-group centroid. $A_i^{\\text{MNL}}$ adds "
        "the commute and the destination walkshed under a mode-choice model. $E_i$ is the time-weighted "
        f"composite day. {n_zero} block groups ({pop_zero:,} residents) have zero cameras within a "
        "ten-minute walk; they are real zeros and enter every statistic. Staten Island shows the largest "
        "gap between residence and activity space."
    )
    return wrap(
        body,
        caption="Sample and exposure by borough.",
        label="tab:descriptives",
        colspec="lrr" + "r" * len(cols),
        note=note,
        source="data/derived/exposure/exposure_table_nyc.csv",
    )


# ---------------------------------------------------------------------------------------
# T8. Income quintiles: the equalization, seen as a gradient that flattens.
# ---------------------------------------------------------------------------------------
def t_quintiles() -> str:
    df = _table()
    df = df[df["median_hh_income"].notna()].copy()

    # Population-weighted quintiles: cut on the CDF of people, not of block groups, so each
    # bin holds a fifth of New Yorkers rather than a fifth of polygons.
    df = df.sort_values("median_hh_income")
    cw = df["population"].cumsum() / df["population"].sum()
    df["q"] = np.minimum((cw * 5).astype(int) + 1, 5)

    cols = [c for c in ("R_i", "A_mnl", "E_i") if c in df.columns]
    tex = {"R_i": r"$R_i$", "A_mnl": r"$A_i^{\text{MNL}}$", "E_i": r"$E_i$"}
    body = "    Measure & " + " & ".join(f"Q{i}" for i in range(1, 6)) + " & Q1/Q5 \\\\\n    \\midrule\n"
    body += (
        "    Household income & "
        + " & ".join(
            f"\\${np.average(df[df.q == i]['median_hh_income'], weights=df[df.q == i]['population']) / 1000:.0f}k"
            for i in range(1, 6)
        )
        + " & \\\\\n    \\midrule\n"
    )
    for c in cols:
        vals = []
        for i in range(1, 6):
            g = df[df.q == i]
            m = g[c].notna()
            vals.append(float(np.average(g[c][m], weights=g["population"][m])) if m.any() else float("nan"))
        ratio = vals[0] / vals[4] if vals[4] else float("nan")
        body += f"    {tex[c]} & " + " & ".join(f"{v:.1f}" for v in vals) + f" & {ratio:.2f} \\\\\n"
    note = (
        "Quintiles of the population, not of block groups: each column holds a fifth of the New Yorkers "
        "living in block groups that report income. The income row is the population-weighted mean of "
        "block-group median household income within each quintile. Exposure entries are population-weighted "
        "mean distinct cameras. The residential gradient is not monotone, because the highest-income "
        "quintile is concentrated in the dense, heavily surveilled core; the activity-space gradient is "
        "close to flat."
    )
    return wrap(
        body,
        caption="Exposure by income quintile. The residential gradient flattens in activity space.",
        label="tab:quintiles",
        colspec="lrrrrrr",
        note=note,
        source="data/derived/exposure/exposure_table_nyc.csv",
    )


