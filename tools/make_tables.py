def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if any table on disk differs")
    args = ap.parse_args()

    TABLES.mkdir(parents=True, exist_ok=True)
    stale = []
    for name, fn in TABLES_TO_WRITE.items():
        tex = fn()
        if not tex:
            continue
        path = TABLES / f"{name}.tex"
        if args.check:
            if not path.exists() or path.read_text() != tex:
                stale.append(name)
        else:
            path.write_text(tex)
            print(f"  wrote {path.relative_to(ROOT)}")

    if args.check:
        if stale:
            print(f"STALE (re-run tools/make_tables.py): {', '.join(stale)}", file=sys.stderr)
            return 1
        print("all tables up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
