# T2. The control ladder: what the disorder narrative can rationalize.
# ---------------------------------------------------------------------------------------
def t_ladder() -> str:
    d = load_json("crime_ladder")
    lad = d["ladders"]["R_i"]
    med = d["mediator_racialization"]
    rungs = [
        ("rung1_total", "(1) No controls"),
        ("rung2_landuse", "(2) + Land use"),
        ("rung3_crime", "(3) + Crime"),
        ("rung4_crime_311", "(4) + Crime + 311"),
    ]
    body = "    Specification & " + " & ".join(t for _, t in FOCALS) + " \\\\\n    \\midrule\n"
    for key, label in rungs:
        cells = []
        for f, _ in FOCALS:
            if f not in lad:
                cells.append("--")
                continue
            b, s = lad[f][key]
            cells.append(f"{signed(b)} ({se(s)})")
        body += f"    {label} & " + " & ".join(cells) + " \\\\\n"
    body += "    \\midrule\n    \\multicolumn{5}{l}{\\emph{The mediators are themselves racialized:}} \\\\\n"
    keymap = {"%Hisp": "pct_hisp", "%Black": "pct_black", "%White": "pct_white", "income": "income"}
    for mk, mlabel in [("log1p(crime)", "Crime density"), ("log1p(311)", "311 disorder density")]:
        cells = []
        for f, _ in FOCALS:
            b, s, _n = med[mk][keymap[f]]
            cells.append(f"{signed(b)} ({se(s)})")
        body += f"    \\quad {mlabel} & " + " & ".join(cells) + " \\\\\n"
    n_dem = lad["%Hisp"]["n"]
    n_inc = lad["income"]["n"]
    note = (
        f"Population-weighted WLS with HC1-robust standard errors (in parentheses). Each column is a "
        f"separate ladder for that focal covariate: specification (1) is the bivariate association, and "
        f"the controls are added to that column's regression alone, so the mediation denominators stay "
        f"well-defined. Coefficients are cameras per standard deviation of the focal covariate. "
        f"$N={n_dem:,}$ for the demographic "
        f"specifications and $N={n_inc:,}$ for income, which the ACS suppresses in roughly 1,040 small "
        f"block groups. The lower panel regresses each mediator on the same focal covariates: both crime "
        f"and 311 complaint density are strongly patterned by ethnicity, so conditioning on them removes "
        f"variation that is itself a product of the disparity under study. We therefore report "
        f"specification (1) as the estimate of interest and the remainder as a decomposition of what the "
        f"disorder rationale can account for, not as a set of confounders to be removed."
    )
    return wrap(
        body,
        caption=(
            "Residential exposure $R_i$ against demographics, adding controls. Conditioning on crime and "
            "311 complaint density absorbs most of the ethnic disparity, but both mediators are themselves "
            "predicted by ethnicity."
        ),
        label="tab:ladder",
        colspec="lrrrr",
        note=note,
        source="data/derived/results/crime_ladder.json",
    )


# ---------------------------------------------------------------------------------------
# T3. Need-neutral counterfactual. Specification-free: no regression, no controls.
# ---------------------------------------------------------------------------------------
def t_counterfactual() -> str:
    d = load_json("counterfactual")
    blocks = d["blocks"]
    race = blocks["Excess exposure by plurality race/ethnicity"]
    inc = blocks["Excess exposure by income quintile"]

    # Exact keys, never fuzzy-matched. `excess_*` is an absolute camera count and `pct_excess_*`
    # is already in percent; an earlier version guessed between them and printed "+714%".
    # A table generator that can silently pick the wrong field is how a wrong number reaches print.
    NEED = ("R_actual", "R_neutral_pop", "pct_excess_pop", "R_neutral_ambient", "pct_excess_ambient")

    def cells(g: dict) -> str:
        missing = [k for k in NEED if k not in g]
        if missing:
            sys.exit(f"counterfactual.json: missing {missing}; have {sorted(g)}")
        return (
            f"{g['R_actual']:.1f} & {g['R_neutral_pop']:.1f} & ${g['pct_excess_pop']:+.1f}\\%$ & "
            f"{g['R_neutral_ambient']:.1f} & ${g['pct_excess_ambient']:+.1f}\\%$"
        )

    body = (
        "    & Observed & \\multicolumn{2}{c}{Need $\\propto$ population} & "
        "\\multicolumn{2}{c}{Need $\\propto$ ambient} \\\\\n"
        "    \\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\n"
        "    Group & $R_i$ & Neutral & Excess & Neutral & Excess \\\\\n"
        "    \\midrule\n"
    )
    for name, g in race.items():
        label = name.split(" (")[0].replace("%", r"\%")
        n = name.split("n=")[1].rstrip(")") if "n=" in name else ""
        body += f"    {label} ($n={n}$) & {cells(g)} \\\\\n"
    body += "    \\midrule\n"
    for name, g in inc.items():
        q = name.split(" (")[0]
        body += f"    Income {q} & {cells(g)} \\\\\n"
    note = (
        "Surveillance intensity is reallocated in proportion to need over the same walksheds, normalized "
        "so that total population-weighted exposure is conserved, and each block group's counterfactual "
        "exposure $R_i^{\\text{neutral}}$ is evaluated on its own walkshed. ``Excess'' is "
        "$100(R_i / R_i^{\\text{neutral}} - 1)$, "
        "population-weighted within each group. Need proportional to ``population'' takes residents alone; "
        "need proportional to ``ambient'' takes residents plus inbound workers, which is the better proxy "
        "for who is actually on the street during the day. The two proxies bracket the estimate: the sign "
        "is stable across both, the magnitude is not. The normalization conserves total population-weighted "
        "exposure, so the mean excess is exactly zero by design. Income quintiles hold a fifth of the "
        "population of income-reporting block groups each, the same construction as "
        "Table~\\ref{tab:quintiles}. This quantity involves no regression "
        "and no covariate selection, and so cannot be attacked on specification grounds."
    )
    return wrap(
        body,
        caption=(
            "Observed exposure against a need-neutral allocation of the same camera stock. Black-plurality "
            "and Hispanic-plurality block groups carry more exposure than need alone predicts; "
            "White-plurality and high-income block groups carry less."
        ),
        label="tab:counterfactual",
        colspec="lrrrrr",
        note=note,
        source="data/derived/results/counterfactual.json",
    )


