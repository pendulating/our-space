# T4. Disparity across measures: the equalization, in coefficients.
# ---------------------------------------------------------------------------------------
def t_disparity_by_measure() -> str:
    d = load_json("crime_ladder")["ladders"]
    order = [("R_i", r"$R_i$ (residential)"), ("E_i", r"$E_i$ (composite day)"), ("A_mnl", r"$A_i^{\text{MNL}}$ (activity space)")]
    body = "    Outcome & " + " & ".join(t for _, t in FOCALS) + " \\\\\n    \\midrule\n"
    for key, tex in order:
        if key not in d:
            continue
        cells = []
        for f, _ in FOCALS:
            b, s = d[key][f]["rung1_total"]
            cells.append(f"{signed(b)} ({se(s)})")
        body += f"    {tex} & " + " & ".join(cells) + " \\\\\n"
    note = (
        "Population-weighted WLS, no controls, HC1-robust standard errors; each cell is a separate "
        "bivariate regression of the row's outcome on the column's covariate. Coefficients are cameras per "
        "standard deviation of the focal covariate, so they are comparable in units across rows but not in "
        "relative terms, because the outcomes have different dispersions. The ethnic gradient that is sharp "
        "in residential exposure is close to zero in activity-space exposure."
    )
    return wrap(
        body,
        caption=(
            "The residential disparity does not survive the commute. The same regression, run against "
            "residence-based, composite, and activity-space exposure."
        ),
        label="tab:disparity-by-measure",
        colspec="lrrrr",
        note=note,
        source="data/derived/results/crime_ladder.json",
    )


