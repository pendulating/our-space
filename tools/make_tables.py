# T5. Occlusion: a characterized null. The reviewer-objection table.
# ---------------------------------------------------------------------------------------
def t_occlusion() -> str:
    d = load_json("occlusion")
    body = (
        "    Assumed range & \\multicolumn{2}{c}{Sightlines removed} & Cameras removed \\\\\n"
        "    \\cmidrule(lr){2-3}\n"
        "    (CCTV / DOT) & Point-level & Path-level & from $R_i$ \\\\\n"
        "    \\midrule\n"
    )
    for r in d["range_sensitivity"]:
        star = r"\;$\star$" if r["range_scale"] == 1 else ""
        body += (
            f"    {r['cctv_range_m']}\\,m / {r['dot_range_m']}\\,m{star} & "
            f"{100 * r['point_level_attenuation']:.2f}\\% & "
            f"{100 * r['path_level_attenuation']:.2f}\\% & "
            f"{r['cameras_killed']:,} \\\\\n"
        )
    h = d["headline"]
    top_point = 100 * d["range_sensitivity"][-1]["point_level_attenuation"]
    note = (
        f"$\\star$ marks the modeled range used throughout the paper. Line of sight is tested against "
        f"{h['walls']:,} building-facade segments from {h['footprints']:,} footprints. ``Point-level'' is the "
        f"fraction of (camera, street-point) sightlines a building blocks; ``path-level'' is the fraction of "
        f"distinct cameras thereby removed from $R_i$. The two differ because a camera is removed only if "
        f"every one of its sightlines into the walkshed is blocked: at the modeled range "
        f"{100 * h['cameras_saved_by_another_sightline'] / (h['cameras_saved_by_another_sightline'] + h['cameras_fully_occluded']):.0f}\\% "
        f"of the cameras occlusion touches at all are blocked at one point on the walk yet still see the "
        f"walker at another. The bottom row is a positive control: the same code, index, and host-building "
        f"logic, with only the range multiplied, removes {top_point:.0f}\\% of all sightlines."
    )
    return wrap(
        body,
        caption=(
            f"Building occlusion, swept over the assumed camera range. At the modeled range it removes "
            f"{100 * h['path_level_attenuation']:.2f}\\% of $R_i$; the effect only becomes material past "
            f"roughly 60\\,m, when a camera's reach leaves the street canyon."
        ),
        label="tab:occlusion",
        wide=False,
        colspec="lrrr",
        note=note,
        source="data/derived/results/occlusion.json",
    )


