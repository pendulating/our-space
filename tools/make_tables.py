#!/usr/bin/env python3
"""Render every LaTeX table in the paper from the persisted result artifacts.

Single source of truth: nothing in `facct27_digital_eyes_on_the_street/tables/` is
hand-edited. Each table is generated here from `data/derived/results/*.json` (written by
the Rust batch + the analysis scripts) or `data/derived/exposure/*.csv`, so a re-bake
propagates to the paper by re-running this file and recompiling. If a number in the paper
cannot be traced to a file this script reads, it does not belong in the paper.

    uv run python tools/make_tables.py            # write tables/*.tex
    uv run python tools/make_tables.py --check    # exit 1 if any table is stale

Every table also emits a `% generated by tools/make_tables.py from <source>` provenance
comment, so a reader of the .tex can find the artifact it came from.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

import numpy as np
import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parent.parent
RESULTS = ROOT / "data/derived/results"
EXPOSURE = ROOT / "data/derived/exposure"
TABLES = ROOT / "facct27_digital_eyes_on_the_street/tables"

# Column order for anything reported by focal covariate. Keep it fixed across tables so a
# reader can scan down the paper without re-learning the layout.
FOCALS = [("%Hisp", r"\%Hispanic"), ("%Black", r"\%Black"), ("%White", r"\%White"), ("income", "Median income")]


def load_json(name: str) -> dict:
    p = RESULTS / f"{name}.json"
    if not p.exists():
        sys.exit(f"missing {p}. Run the analysis scripts first (see {RESULTS}/README.md).")
    return json.loads(p.read_text())


def se(x: float) -> str:
    return f"{x:.2f}"


def signed(x: float, nd: int = 2) -> str:
    """Explicit sign on every coefficient, in math mode.

    A table of disparities is a table of signs, so the sign must be legible: in text mode LaTeX
    renders ``-'' as a hyphen, which is visibly shorter than a minus and sits at the wrong height.
    """
    return f"${x:+.{nd}f}$"


def wrap(
    body: str,
    *,
    caption: str,
    label: str,
    colspec: str,
    note: str = "",
    source: str = "",
    wide: bool = True,
) -> str:
    """Emit one booktabs table.

    `wide` selects `table*` (spans both columns of the ACM two-column layout). Most of these
    tables have five or more numeric columns and will not fit a 3.3in column, so it defaults on.

    The note goes inside a `minipage`, not loose after the `tabular`: `\\centering` is still in
    force at that point, so an unboxed paragraph gets its first line centred and then flows past
    the table's right edge.
    """
    env = "table*" if wide else "table"
    note_tex = (
        f"\n  \\vspace{{3pt}}\n"
        f"  \\begin{{minipage}}{{\\linewidth}}\n"
        f"    \\footnotesize\\raggedright {note}\n"
        f"  \\end{{minipage}}\n"
        if note
        else "\n"
    )
    return (
        f"% !!! GENERATED by tools/make_tables.py from {source}. Do not edit by hand. !!!\n"
        f"% Regenerate:  uv run python tools/make_tables.py\n"
        f"\\begin{{{env}}}[t]\n"
        f"  \\centering\n"
        f"  \\caption{{{caption}}}\n"
        f"  \\label{{{label}}}\n"
        f"  \\small\n"
        f"  \\begin{{tabular}}{{{colspec}}}\n"
        f"    \\toprule\n"
        f"{body}"
        f"    \\bottomrule\n"
        f"  \\end{{tabular}}{note_tex}"
        f"\\end{{{env}}}\n"
    )


# ---------------------------------------------------------------------------------------
# T1. Inequality: the equalization result. The paper's centrepiece table.
# ---------------------------------------------------------------------------------------
def t_inequality() -> str:
    d = load_json("inequality_stats")["measures"]
    rows = [
        ("R_i", r"$R_i$ (residential)", "Where you live"),
        ("A_drive", r"$A_i^{\text{drive}}$", "Where you go (drive)"),
        ("A_modal", r"$A_i^{\text{modal}}$", "Where you go (observed modes)"),
        ("A_mnl", r"$A_i^{\text{MNL}}$", "Where you go (modeled modes)"),
        ("E_i", r"$E_i$ (composite day)", "Time-weighted day"),
    ]
    body = (
        "    Measure & Interpretation & Mean & Gini & Top 10\\% & P90/P10 \\\\\n"
        "    \\midrule\n"
    )
    for key, tex, interp in rows:
        if key not in d:
            continue
        m = d[key]
        p90, p10 = m["p90"], m["p10"]
        ratio = p90 / p10 if p10 > 0 else float("nan")
        body += (
            f"    {tex} & {interp} & {m['mean_popwtd']:.1f} & {m['gini_popwtd']:.3f} & "
            f"{100 * m['top_decile_share_popwtd']:.1f}\\% & {ratio:.2f}$\\times$ \\\\\n"
        )
    note = (
        "All statistics are population-weighted, so each is a statement about people rather than about "
        "block groups. ``Top 10\\%'' is the share of total exposure borne by the decile of the population "
        "with the highest exposure; 10\\% would indicate perfect equality. P90/P10 is the ratio of the "
        "90th to the 10th population-weighted percentile."
    )
    # The caption states the two headline ratios, so it is computed, not typed: a hand-written
    # "roughly eight times" silently becomes wrong the first time the pipeline is re-baked.
    r_ri = d["R_i"]["p90"] / d["R_i"]["p10"]
    r_am = d["A_mnl"]["p90"] / d["A_mnl"]["p10"]
    return wrap(
        body,
        caption=(
            "Exposure inequality collapses when exposure is measured over a trajectory rather than at a "
            f"residence. A New Yorker at the 90th percentile of residential exposure lives under "
            f"{r_ri:.1f} times the cameras of one at the 10th percentile, but moves through only "
            f"{r_am:.2f} times as many."
        ),
        label="tab:inequality",
        colspec="llrrrr",
        note=note,
        source="data/derived/results/inequality_stats.json",
    )


