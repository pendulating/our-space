# T9. Network descriptives. Documents the drive/walk split the instrument depends on.
# ---------------------------------------------------------------------------------------
def t_networks() -> str:
    src = RESULTS / "graph_stats.json"
    if not src.exists():
        return ""  # optional; emitted by tools/emit_graph_stats.sh
    d = json.loads(src.read_text())
    classes = ["Street", "Highway", "Ramp", "Bridge", "Tunnel", "Alley", "Path/Trail", "Boardwalk", "Step"]
    body = "    Class & Drive network (km) & Walk network (km) \\\\\n    \\midrule\n"
    for c in classes:
        dv = d["drive"]["km"].get(c)
        wk = d["walk"]["km"].get(c)
        if dv is None and wk is None:
            continue
        body += f"    {c} & {('--' if dv is None else f'{dv:,.0f}')} & {('--' if wk is None else f'{wk:,.0f}')} \\\\\n"
    body += (
        "    \\midrule\n"
        f"    Nodes & {d['drive']['nodes']:,} & {d['walk']['nodes']:,} \\\\\n"
        f"    Edges & {d['drive']['edges']:,} & {d['walk']['edges']:,} \\\\\n"
    )
    note = (
        "Both networks are derived from the NYC Street Centerline (CSCL) file by complementary "
        "classifiers: the drive network excludes segments CSCL flags as non-vehicular "
        "(\\texttt{trafdir=NV}), and the walk network excludes those it flags as non-pedestrian "
        "(\\texttt{nonped=V}). The Brooklyn Bridge illustrates the distinction: its roadway carries "
        "\\texttt{nonped=V} and its promenade \\texttt{trafdir=NV}, so each network retains exactly one. "
        "Every walkshed in this paper is computed on the walk network; commute routes are computed on the "
        "drive network."
    )
    return wrap(
        body,
        caption="The two street networks. Walksheds computed on a drive network would traverse limited-access highway and miss park paths.",
        label="tab:networks",
        wide=False,
        colspec="lrr",
        note=note,
        source="data/derived/results/graph_stats.json",
    )


