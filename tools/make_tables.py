# T6. Undercount. The correction is a robustness result, not an amplification result.
# ---------------------------------------------------------------------------------------
def t_recall() -> str:
    cr = load_json("capture_recapture")
    g, b = cr["global"], cr["bootstrap_95"]
    dis = cr["disparity_under_correction"]
    body = (
        "    \\multicolumn{4}{l}{\\emph{(a) Two-source estimate of the camera census}} \\\\\n"
        "    \\midrule\n"
        f"    Observed (merged census) & \\multicolumn{{3}}{{r}}{{{g['observed']:,.0f}}} \\\\\n"
        f"    Chapman $\\hat{{N}}$ & \\multicolumn{{3}}{{r}}{{{g['N']:,.0f}}} "
        f"[{b['N_lo']:,.0f}, {b['N_hi']:,.0f}] \\\\\n"
        f"    Implied recall $r$ & \\multicolumn{{3}}{{r}}{{{g['recall']:.3f}}} "
        f"[{b['recall_lo']:.3f}, {b['recall_hi']:.3f}] \\\\\n"
        "    \\midrule\n"
        "    \\multicolumn{4}{l}{\\emph{(b) Effect of correcting for it}} \\\\\n"
        "    \\midrule\n"
        "    & Mean $R_i$ & $\\rho$(\\%Hisp) & $\\rho$(income) \\\\\n"
        "    \\midrule\n"
    )
    for key, label in [("raw", "Observed counts"), ("global", "Uniform recall"), ("spatial", "Borough-varying recall")]:
        if key not in dis:
            continue
        m = dis[key]
        body += (
            f"    {label} & {m['mean_R']:.1f} & {signed(m['corr_hispanic'], 3)} & "
            f"{signed(m['corr_income'], 3)} \\\\\n"
        )
    note = (
        "Panel (a): Chapman two-source estimator over the Amnesty crowdsourced census and the Dahir et al.\\ "
        "detector census; brackets are bootstrap 95\\% intervals. Panel (b): the correction inflates only "
        "camera groups no surveyed source attests, so exposure rescales by roughly $1/r \\approx 1.9$ and "
        "any coefficient in cameras per standard deviation inflates with it. We therefore report the "
        "scale-free correlations. The focal \\%Hispanic correlation barely moves; the income correlation "
        "moves somewhat more because the surveyed layers that confirm a group are Manhattan-concentrated, "
        "so the correction inflates the outer boroughs relatively more (the enforcement-layer disclosure "
        "in the robustness discussion is the same fact). The correction changes the units of the disparity, "
        "not its magnitude. Both censuses derive from Google Street View, so their overlap is positively "
        "dependent and $\\hat{N}$ is, if anything, an underestimate of the true count."
    )
    return wrap(
        body,
        caption=(
            "Camera-census undercount and its effect on the disparity. Correcting for an estimated 50\\% "
            "recall rescales exposure but leaves the relative disparity essentially unchanged."
        ),
        label="tab:recall",
        wide=False,
        colspec="lrrr",
        note=note,
        source="data/derived/results/capture_recapture.json",
    )


